import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import converter from "swagger2openapi";

// Generate src/types/api.gen.ts from the backend Swagger 2.0 spec
const specPath = process.env.API_SPEC ?? "../Go-Backend-Stock/docs/api/swagger.json";
const outPath = "src/types/api.gen.ts";

const swagger = JSON.parse(await readFile(specPath, "utf8"));
const { openapi } = await converter.convertObj(swagger, { patch: true, warnOnly: true });
const header = "// Generated by `npm run gen:api` from Go-Backend-Stock docs/api/swagger.json. Do not edit.\n\n";
await writeFile(outPath, header + astToString(await openapiTS(openapi)));
console.log(`Wrote ${outPath}`);
